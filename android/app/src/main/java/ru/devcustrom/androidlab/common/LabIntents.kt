package ru.devcustrom.androidlab.common

/**
 * Ключи `Intent` в одном месте.
 *
 * Строки в `putExtra("student_name", …)` — это **неявный контракт** между двумя
 * классами: переименуешь строку в одном файле, а второй молча перестанет
 * получать значение, и ошибка всплывёт только в рантайме. Именно так и появилась
 * грабля «одна и та же строка в двух файлах», поэтому все ключи вынесены сюда.
 */
object LabIntents {
    /** Имя студента: `MainActivity` отправляет, экраны лаб читают. */
    const val EXTRA_STUDENT_NAME = "student_name"

    /** Последняя посчитанная строка: `Lab1Activity` возвращает, главный экран читает. */
    const val EXTRA_LAST_VALUE = "last_value"
}